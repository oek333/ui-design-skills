#!/bin/bash
# Regenerates each case's scaffold.sh from the readable apps in fixtures/.
# The eval runner starts every run in an empty workspace and only executes the
# case's scaffold script, so each script carries its app as an embedded archive.
set -euo pipefail
cd "$(dirname "$0")"

build() { # <fixture dir> <case dir>
  local b64
  b64=$(cd "fixtures/$1" && COPYFILE_DISABLE=1 tar czf - . | base64)
  {
    printf '#!/bin/bash\nset -e\n# Generated by build-scaffolds.sh from evals/fixtures/%s. Do not edit.\n' "$1"
    printf "base64 -d <<'EOF' | tar xzf -\n%s\nEOF\n" "$b64"
  } > "$2/scaffold.sh"
  chmod +x "$2/scaffold.sh"
}

build editorial-board        board-friction-review
build collation-desk-patched coherent-century-filter
build collation-desk         collation-timeline-prototype
